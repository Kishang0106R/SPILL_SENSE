"""
Spill Sense Database Layer - PostgreSQL Persistence
Handles tables for spills, vessels, investigations, analyst notes, and analytics.
"""

import json
import os
from typing import List, Dict, Any, Optional

import psycopg
from psycopg.rows import dict_row

def get_connection():
    database_url = os.getenv(
        "DATABASE_URL",
        "postgresql://postgres:postgres@localhost:5432/spillguard",
    )
    return psycopg.connect(database_url, row_factory=dict_row)

def init_db():
    conn = get_connection()
    cursor = conn.cursor()

    # 1. Spills Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS spills (
            id TEXT PRIMARY KEY,
            title TEXT NOT NULL,
            severity TEXT NOT NULL,
            status TEXT NOT NULL,
            lat REAL NOT NULL,
            lon REAL NOT NULL,
            area_km2 REAL NOT NULL,
            volume_bbls INTEGER NOT NULL,
            confidence REAL NOT NULL,
            sensor TEXT NOT NULL,
            detected_at TEXT NOT NULL,
            wind TEXT NOT NULL,
            current TEXT NOT NULL,
            surface_temp TEXT NOT NULL,
            slick_type TEXT NOT NULL,
            thumbnail TEXT NOT NULL,
            primary_suspect_json TEXT NOT NULL,
            polygon_json TEXT NOT NULL
        )
    """)

    # 2. Vessels Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS vessels (
            imo INTEGER PRIMARY KEY,
            name TEXT NOT NULL,
            mmsi INTEGER NOT NULL,
            call_sign TEXT NOT NULL,
            flag TEXT NOT NULL,
            flag_code TEXT NOT NULL,
            type TEXT NOT NULL,
            length TEXT NOT NULL,
            beam TEXT NOT NULL,
            dwt TEXT NOT NULL,
            lat REAL NOT NULL,
            lon REAL NOT NULL,
            heading INTEGER NOT NULL,
            speed REAL NOT NULL,
            draft TEXT NOT NULL,
            last_ping TEXT NOT NULL,
            signal_health TEXT NOT NULL,
            is_dark INTEGER NOT NULL,
            dark_duration TEXT NOT NULL,
            risk_score INTEGER NOT NULL,
            risk_level TEXT NOT NULL,
            track_history_json TEXT NOT NULL
        )
    """)

    # 3. Investigations Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS investigations (
            incident_id TEXT PRIMARY KEY,
            case_code TEXT NOT NULL,
            classification TEXT NOT NULL,
            location_desc TEXT NOT NULL,
            lat_long TEXT NOT NULL,
            satellite_json TEXT NOT NULL,
            metocean_json TEXT NOT NULL,
            forensics_json TEXT NOT NULL,
            drift_sim_json TEXT NOT NULL,
            candidates_json TEXT NOT NULL
        )
    """)

    # 4. Analyst Notes Table (Persistent Operator Entries)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS vessel_notes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            imo INTEGER NOT NULL,
            note_text TEXT NOT NULL,
            author TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (imo) REFERENCES vessels(imo)
        )
    """)

    # 5. Analytics Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS analytics (
            id INTEGER PRIMARY KEY,
            kpis_json TEXT NOT NULL,
            monthly_trend_json TEXT NOT NULL,
            regional_dist_json TEXT NOT NULL,
            top_fleets_json TEXT NOT NULL
        )
    """)

    # 6. Feedback Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS feedback (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT,
            email TEXT,
            feedback_type TEXT NOT NULL,
            rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
            message TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    conn.commit()

    # Seed default data if empty
    cursor.execute("SELECT COUNT(*) AS spill_count FROM spills")
    if cursor.fetchone()["spill_count"] == 0:
        seed_initial_data(cursor)
        conn.commit()

    conn.close()

